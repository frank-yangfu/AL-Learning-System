def get_seed_questions(course_id):
    """返回指定 course_id 的种子题库数据（供 server.py 组卷调用）。
    返回 None 表示该知识点不在种子库中。"""
    return SEED_BANK.get(course_id)


def list_seed_topics():
    """列出所有已覆盖的知识点 ID 和标题。"""
    return [(cid, v["title"], v["subject"]) for cid, v in SEED_BANK.items()]
