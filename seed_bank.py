# ─── 辅助函数 ──────────────────────────────────────────────
def _cq(t, o, a, e):
    """构造选择题。"""
    return {"type": "choice", "stem": t, "options": list(o), "answer": a, "explanation": e}

def _fq(t, a, e):
    """构造填空/计算题。"""
    return {"type": "fill", "stem": t, "options": [], "answer": str(a), "explanation": e}

